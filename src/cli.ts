#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CONFIG_FILE, defaultConfig, loadConfig, saveConfig } from './config.ts';
import { doctor, formatDoctor } from './doctor.ts';
import { assertTopLevel } from './guard.ts';
import { Ledger, loadLearned, saveLearned } from './ledger.ts';
import { cleanRun, latestRunId, loadState, Runner, summarize } from './runner.ts';
import { loadTasks, topoOrder } from './tasks.ts';
import type { RunState } from './types.ts';
import { excludeStateDir, git, gitOk, repoRoot } from './worktree.ts';

const VERSION = '0.1.0';

const HELP = `polyagent ${VERSION} — Claude-led delegation across Claude, Codex and Antigravity/Gemini

Usage: polyagent <command> [options]

  init                     Create ${CONFIG_FILE} and exclude .polyagent/ from git
  doctor [--refresh|--force-models] [--reset]
                           Check CLIs and sign-in, discover models, write tier→model maps;
                           --reset re-enables providers disabled after an account error
  plan <tasks.json>        Dry run: tiers, routing, models. Calls no model.
  run <tasks.json> [--claude-low] [--concurrency N]
                           Run tasks in worktrees; prints a compact JSON summary
  status [runId]           Summary of a run (default: latest)
  resume [runId]           Continue a stopped run
  merge [runId] [--tasks a,b]
                           Merge passed task branches into the current branch
  clean [runId] [--force]  Remove worktrees (and merged branches; --force: all branches)
  ledger [--json]          Usage per provider, model and tier
  sync-rules [--from CLAUDE.md] [--force]
                           Copy project rules to AGENTS.md and GEMINI.md

Exit codes: 0 ok, 1 error, 2 some tasks failed, 3 stopped on budget.`;

function flag(args: string[], name: string): boolean {
  const i = args.indexOf(name);
  if (i >= 0) args.splice(i, 1);
  return i >= 0;
}

function opt(args: string[], name: string): string | undefined {
  const i = args.indexOf(name);
  if (i < 0) return undefined;
  const v = args[i + 1];
  args.splice(i, 2);
  return v;
}

function print(o: unknown) {
  process.stdout.write(JSON.stringify(o, null, 2) + '\n');
}

function exitFor(s: RunState): number {
  if (s.stopped) return 3;
  return Object.values(s.tasks).some((t) => t.status === 'failed' || t.status === 'blocked') ? 2 : 0;
}

function pickRun(repo: string, id?: string): string {
  const r = id ?? latestRunId(repo);
  if (!r) throw new Error('no runs yet');
  return r;
}

const GEN_HEADER = '<!-- generated by polyagent sync-rules from';

async function main(argv: string[]): Promise<number> {
  assertTopLevel();
  const args = [...argv];
  const cmd = args.shift();
  if (!cmd || cmd === '-h' || cmd === '--help' || cmd === 'help') {
    console.log(HELP);
    return 0;
  }
  if (cmd === '--version' || cmd === '-v') {
    console.log(VERSION);
    return 0;
  }
  const repo = repoRoot(process.cwd());

  switch (cmd) {
    case 'init': {
      excludeStateDir(repo);
      const f = join(repo, CONFIG_FILE);
      if (existsSync(f)) console.log(`${CONFIG_FILE} already exists; left unchanged.`);
      else {
        saveConfig(repo, defaultConfig());
        console.log(`wrote ${CONFIG_FILE}. Next: polyagent doctor --refresh`);
      }
      return 0;
    }
    case 'doctor': {
      const cfg = loadConfig(repo);
      const mode = flag(args, '--force-models') ? 'force' : flag(args, '--refresh') ? 'fill' : false;
      const learned = loadLearned(repo);
      if (flag(args, '--reset')) {
        learned.disabled = {};
        learned.cooldownUntil = {};
        saveLearned(repo, learned);
        console.log('cleared disabled providers and cooldowns.\n');
      }
      const reps = doctor(cfg, repo, mode);
      for (const r of reps) {
        const why = learned.disabled?.[r.id];
        if (why) r.problems.push(`disabled after the provider refused this account: ${why.slice(0, 160)} (fix sign-in, then polyagent doctor --reset)`);
        const cd = learned.cooldownUntil[r.id];
        if (cd && Date.parse(cd) > Date.now()) r.problems.push(`cooling down after a usage limit until ${cd}`);
      }
      console.log(formatDoctor(reps));
      if (mode) {
        saveConfig(repo, cfg);
        console.log(`\nupdated tier maps in ${CONFIG_FILE} (edit it to override any choice).`);
      }
      const bad = reps.filter((r) => r.enabled && (!r.binary || r.auth === 'missing'));
      return bad.length ? 1 : 0;
    }
    case 'plan': {
      const file = args.shift();
      if (!file) throw new Error('usage: polyagent plan <tasks.json>');
      const cfg = loadConfig(repo);
      const tf = loadTasks(file);
      const claudeLow = flag(args, '--claude-low');
      const r = Runner.create(repo, cfg, tf, file, { claudeLow });
      const rows = r.preview();
      // Dry runs must not leave a run behind.
      const { rmSync } = await import('node:fs');
      rmSync(join(repo, '.polyagent', 'runs', r.state.runId), { recursive: true, force: true });
      print({
        tasks: rows.map((x) => ({ id: x.id, tier: x.tier, tierNotes: x.tierNotes.length ? x.tierNotes : undefined, ...(x.route.kind === 'worker' ? { provider: x.route.provider, model: x.route.model ?? 'default', effort: x.route.effort, overflow: x.route.overflow || undefined } : { route: x.route.kind }), why: x.route.why })),
        order: topoOrder(tf.tasks).map((t) => t.id),
      });
      return 0;
    }
    case 'run': {
      const file = args.shift();
      if (!file) throw new Error('usage: polyagent run <tasks.json>');
      const cfg = loadConfig(repo);
      const tf = loadTasks(file);
      const claudeLow = flag(args, '--claude-low');
      const c = opt(args, '--concurrency');
      const r = Runner.create(repo, cfg, tf, file, { claudeLow, concurrency: c ? Number(c) : undefined });
      process.stderr.write(`run ${r.state.runId} started (${tf.tasks.length} tasks)\n`);
      const s = await r.run();
      print(summarize(repo, s, cfg));
      return exitFor(s);
    }
    case 'status': {
      const cfg = loadConfig(repo);
      const s = loadState(repo, pickRun(repo, args.shift()));
      print(summarize(repo, s, cfg));
      return 0;
    }
    case 'resume': {
      const cfg = loadConfig(repo);
      const s = loadState(repo, pickRun(repo, args.shift()));
      const tf = JSON.parse(readFileSync(join(repo, '.polyagent', 'runs', s.runId, 'tasks.json'), 'utf8'));
      if (flag(args, '--claude-low')) s.claudeLow = true;
      const r = new Runner(repo, cfg, tf, s);
      const out = await r.run();
      print(summarize(repo, out, cfg));
      return exitFor(out);
    }
    case 'merge': {
      const cfg = loadConfig(repo);
      const only = opt(args, '--tasks')?.split(',').map((s) => s.trim());
      const s = loadState(repo, pickRun(repo, args.shift()));
      const dirty = git(repo, 'status', '--porcelain').split('\n').filter((l) => l && !l.includes('.polyagent/'));
      if (dirty.length) throw new Error(`working tree not clean; commit or stash first:\n${dirty.slice(0, 10).join('\n')}`);
      const tf = JSON.parse(readFileSync(join(repo, '.polyagent', 'runs', s.runId, 'tasks.json'), 'utf8'));
      const merged: string[] = [];
      for (const t of topoOrder(tf.tasks)) {
        const ts = s.tasks[t.id]!;
        if (only && !only.includes(t.id)) continue;
        if (!ts.branch || !(ts.status === 'passed' || ts.status === 'unverified')) continue;
        if (!gitOk(repo, 'merge', '--no-ff', '--no-edit', '-m', `polyagent: merge ${t.id} (${t.title})`, ts.branch)) {
          gitOk(repo, 'merge', '--abort');
          writeFileSync(join(repo, '.polyagent', 'runs', s.runId, 'state.json'), JSON.stringify(s, null, 2));
          print({ merged, conflict: t.id, hint: `resolve by hand: git merge ${ts.branch}` });
          return 2;
        }
        ts.status = 'merged';
        merged.push(t.id);
      }
      writeFileSync(join(repo, '.polyagent', 'runs', s.runId, 'state.json'), JSON.stringify(s, null, 2));
      void cfg;
      print({ merged });
      return 0;
    }
    case 'clean': {
      const force = flag(args, '--force');
      const s = loadState(repo, pickRun(repo, args.shift()));
      print({ removed: cleanRun(repo, s, force) });
      return 0;
    }
    case 'ledger': {
      const cfg = loadConfig(repo);
      const l = new Ledger(repo).all();
      const agg = new Map<string, { runs: number; ok: number; input: number; output: number; estimated: number }>();
      for (const e of l) {
        const k = `${e.provider}|${e.model ?? 'default'}|${e.tier}`;
        const a = agg.get(k) ?? { runs: 0, ok: 0, input: 0, output: 0, estimated: 0 };
        a.runs++;
        if (e.outcome === 'pass' || e.outcome === 'unverified') a.ok++;
        a.input += e.input;
        a.output += e.output;
        if (e.estimated) a.estimated++;
        agg.set(k, a);
      }
      const rows = [...agg.entries()].map(([k, v]) => {
        const [provider, model, tier] = k.split('|');
        return { provider, model, tier, ...v, passRate: v.runs ? `${Math.round((v.ok / v.runs) * 100)}%` : '-' };
      });
      print({ rows, learned: loadLearned(repo), windows: Object.fromEntries(Object.entries(cfg.providers).map(([p, c]) => [p, c.budget])) });
      return 0;
    }
    case 'sync-rules': {
      const from = opt(args, '--from') ?? 'CLAUDE.md';
      const force = flag(args, '--force');
      const src = join(repo, from);
      if (!existsSync(src)) throw new Error(`${from} not found`);
      const body = readFileSync(src, 'utf8');
      const done: string[] = [];
      for (const target of ['CLAUDE.md', 'AGENTS.md', 'GEMINI.md'].filter((t) => t !== from)) {
        const f = join(repo, target);
        if (existsSync(f) && !force && !readFileSync(f, 'utf8').startsWith(GEN_HEADER)) {
          done.push(`${target}: skipped (hand-written; use --force)`);
          continue;
        }
        writeFileSync(f, `${GEN_HEADER} ${from}; edit ${from} instead -->\n${body}`);
        done.push(`${target}: written`);
      }
      console.log(done.join('\n'));
      return 0;
    }
    default:
      console.error(`unknown command "${cmd}"\n\n${HELP}`);
      return 1;
  }
}

main(process.argv.slice(2)).then(
  (code) => process.exit(code),
  (e) => {
    console.error(`polyagent: ${(e as Error).message}`);
    process.exit(1);
  },
);
